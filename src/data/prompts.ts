export function getRandomPrompt(excludePrompt?: string): string {
  const filtered = excludePrompt ? DAILY_PROMPTS.filter(p => p !== excludePrompt) : DAILY_PROMPTS;
  const index = Math.floor(Math.random() * filtered.length);
  return filtered[index] || DAILY_PROMPTS[0];
}
